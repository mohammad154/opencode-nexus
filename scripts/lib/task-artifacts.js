/**
 * Deterministic `task-N.md` materialization (PR5.C).
 *
 * Before PR5 the planner wrote the same semantic content twice: once into
 * `PLAN.md` and once into each `.opencode/tasks/task-N.md`. Two hand-written
 * copies of one plan are two chances to disagree, and the second copy costs
 * planning tokens without adding authority.
 *
 * After PR5 there is exactly one semantic planning authority:
 *
 *   PLAN.md → parsePlanMarkdown()/normalizePlan() → task materializer → task-N.md
 *
 * `task-N.md` is therefore a *generated execution view*, not a source of truth:
 *
 * - PLAN.md   = semantic planning authority
 * - run state = execution authority
 * - task-N.md = generated compatibility/execution view
 *
 * Safety rules:
 * 1. No second parser. Parsing stays in `plan-check.js`.
 * 2. Every generated file is bound to the PLAN digest and its unit id, so a
 *    stale view is detectable rather than silently trusted.
 * 3. Nexus only removes files it can prove it generated (the `GENERATED BY
 *    NEXUS` header with a recorded source and digest). A user-authored file
 *    under `.opencode/tasks` is never deleted or overwritten.
 */
import fs from "node:fs";
import path from "node:path";
import { sha256Digest } from "./artifact-seal.js";
import { normalizePlan } from "./plan-check.js";
import { validateContainedPath, boundaryError } from "./filesystem-boundary.js";

export const TASK_ARTIFACT_VERSION = "nexus-task-artifact/1";
export const TASK_ARTIFACT_DIR = ".opencode/tasks";
export const GENERATED_HEADER_MARKER = "GENERATED BY NEXUS";
export const CANONICAL_PLAN_RELATIVE_PATH = ".opencode/plans/PLAN.md";

function clean(value) {
  return String(value ?? "").replace(/\r$/, "").trim();
}

function posix(value) {
  return clean(value).replace(/\\/g, "/");
}

/** Digest of the exact plan text a view was generated from. */
export function planTextDigest(planText) {
  return sha256Digest(String(planText ?? ""));
}

function bulletList(items, fallback) {
  const values = (Array.isArray(items) ? items : [])
    .map(clean)
    .filter(Boolean);
  if (values.length === 0) return [`- ${fallback}`];
  return values.map((value) => `- ${value}`);
}

function numberedList(items, fallback) {
  const values = (Array.isArray(items) ? items : [])
    .map(clean)
    .filter(Boolean);
  if (values.length === 0) return [`1. ${fallback}`];
  return values.map((value, index) => `${index + 1}. ${value}`);
}

function metadataLine(label, value) {
  if (value === undefined || value === null || value === "") return null;
  return `- ${label}: ${value}`;
}

/**
 * Render one execution unit as its generated execution view.
 *
 * Pure: the same plan text and unit always produce byte-identical output, which
 * is what makes regeneration idempotent and drift detectable.
 */
export function renderTaskArtifact({
  unit,
  index = 0,
  planPath = CANONICAL_PLAN_RELATIVE_PATH,
  planDigest,
  planningMode = null,
  planCommit = null,
  goal = null,
  nonGoals = [],
} = {}) {
  const source = unit && typeof unit === "object" ? unit : {};
  const id = clean(source.id) || `unit-${index + 1}`;
  const title = clean(source.title) || id;
  const header = [
    `<!-- ${GENERATED_HEADER_MARKER}`,
    `source: ${posix(planPath)}`,
    `plan_digest: ${clean(planDigest) || "unavailable"}`,
    `unit_id: ${id}`,
    `generator: ${TASK_ARTIFACT_VERSION}`,
    "do_not_edit: regenerate from PLAN.md; edits here are not planning authority",
    "-->",
  ];

  const metadata = [
    metadataLine("id", id),
    metadataLine("planning_mode", planningMode),
    metadataLine("plan_commit", planCommit),
    metadataLine(
      "depends_on",
      Array.isArray(source.depends_on) && source.depends_on.length > 0
        ? source.depends_on.join(", ")
        : "none",
    ),
    metadataLine("user_outcome", source.user_outcome),
    metadataLine(
      "independently_shippable",
      typeof source.independently_shippable === "boolean"
        ? String(source.independently_shippable)
        : source.independently_shippable,
    ),
    metadataLine("review_boundary", source.review_boundary),
    metadataLine("estimated_lines", source.estimated_lines),
    metadataLine("effort", source.effort),
    metadataLine("confidence", source.confidence),
    metadataLine("risk_if_wrong", source.risk),
  ].filter(Boolean);

  const body = [
    `# ${id} — ${title}`,
    "",
    "## Unit metadata",
    ...metadata,
    "",
    "## Plan context",
    `- Goal: ${clean(goal) || "see PLAN.md"}`,
    ...bulletList(
      (Array.isArray(nonGoals) ? nonGoals : []).map((entry) => `Non-goal: ${clean(entry)}`),
      "Non-goal: see PLAN.md",
    ),
    "",
    "## Allowed files",
    ...bulletList(source.allowed_files, "none declared in PLAN.md"),
    "",
    "## Evidence",
    ...bulletList(source.evidence, "none declared in PLAN.md"),
    "",
    "## Acceptance criteria",
    ...(Array.isArray(source.acceptance_criteria) && source.acceptance_criteria.length > 0
      ? source.acceptance_criteria.map((item) => `- [ ] ${clean(item)}`)
      : ["- [ ] none declared in PLAN.md"]),
    "",
    "## Verification gates",
    ...numberedList(source.verification_gates, "none declared in PLAN.md"),
    "",
    "## STOP conditions",
    ...bulletList(source.stop_conditions, "STOP if PLAN.md no longer matches the repository."),
    "",
  ];

  return `${[...header, "", ...body].join("\n")}`;
}

/** Parse the generated header of an existing file, if it has one. */
export function readGeneratedHeader(content) {
  const text = String(content ?? "");
  if (!text.startsWith(`<!-- ${GENERATED_HEADER_MARKER}`)) return null;
  const end = text.indexOf("-->");
  if (end < 0) return null;
  const header = text.slice(0, end);
  const field = (name) => {
    const match = header.match(new RegExp(`^${name}:\\s*(.+)$`, "im"));
    return match ? clean(match[1]) : null;
  };
  return {
    source: field("source"),
    plan_digest: field("plan_digest"),
    unit_id: field("unit_id"),
    generator: field("generator"),
  };
}

/**
 * Whether Nexus can prove it generated `content`. Proof is the header contract:
 * marker, recorded source, plan digest, and unit id. Anything else is treated
 * as user-authored and left untouched.
 */
export function isNexusGenerated(content) {
  const header = readGeneratedHeader(content);
  return Boolean(header?.source && header?.plan_digest && header?.unit_id);
}

function taskFileName(index) {
  return `task-${index + 1}.md`;
}

function readIfPresent(file) {
  try {
    return fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
}

/**
 * Materialize every execution unit of the canonical plan into
 * `.opencode/tasks/task-N.md`.
 *
 * @param {object} options
 * @param {string} options.worktree project root
 * @param {string} [options.planPath] absolute or worktree-relative PLAN.md
 * @param {string} [options.planText] plan text (skips reading the file)
 * @param {object} [options.plan] pre-normalized plan/plan-check result
 * @param {object} [options.telemetry] telemetry provider with `emit`
 * @param {string} [options.runId] run id for telemetry correlation
 * @param {boolean} [options.dryRun] compute without writing
 * @returns {object} deterministic materialization summary
 */
export function materializeTaskArtifacts(options = {}) {
  const started = Date.now();
  const root = path.resolve(options.worktree || process.cwd());
  const requestedPlan = options.planPath || CANONICAL_PLAN_RELATIVE_PATH;
  const planAbsolute = path.isAbsolute(requestedPlan)
    ? requestedPlan
    : path.join(root, requestedPlan);
  const planBoundary = validateContainedPath(root, planAbsolute, {
    allowMissing: true,
    rejectSymlinks: true,
  });
  if (!planBoundary.ok) {
    return {
      ok: false,
      reason: "PLAN_PATH_REJECTED",
      error: boundaryError("plan path", planBoundary).message,
      tasks: [],
      removed: [],
      preserved: [],
      task_materialization_count: 0,
      generated_task_bytes: 0,
      plan_bytes: 0,
      duration_ms: Date.now() - started,
    };
  }

  let planText = options.planText;
  if (typeof planText !== "string") {
    planText = readIfPresent(planAbsolute);
  }
  if (typeof planText !== "string" && !options.plan) {
    return {
      ok: false,
      reason: "PLAN_NOT_FOUND",
      plan_path: posix(path.relative(root, planAbsolute)),
      tasks: [],
      removed: [],
      preserved: [],
      task_materialization_count: 0,
      generated_task_bytes: 0,
      plan_bytes: 0,
      duration_ms: Date.now() - started,
    };
  }

  const normalized = normalizePlan(
    options.plan && typeof options.plan === "object" ? options.plan : planText,
  );
  const units = Array.isArray(normalized.execution_units)
    ? normalized.execution_units
    : [];
  const sourceText =
    typeof planText === "string" ? planText : String(normalized.text ?? "");
  const digest = planTextDigest(sourceText);
  const planRelative = posix(path.relative(root, planAbsolute));

  const tasksDir = path.join(root, TASK_ARTIFACT_DIR);
  const dirBoundary = validateContainedPath(root, tasksDir, {
    allowMissing: true,
    rejectSymlinks: true,
  });
  if (!dirBoundary.ok) {
    return {
      ok: false,
      reason: "TASKS_DIR_REJECTED",
      error: boundaryError("tasks directory", dirBoundary).message,
      plan_path: planRelative,
      plan_digest: digest,
      tasks: [],
      removed: [],
      preserved: [],
      task_materialization_count: 0,
      generated_task_bytes: 0,
      plan_bytes: Buffer.byteLength(sourceText, "utf8"),
      duration_ms: Date.now() - started,
    };
  }

  const dryRun = options.dryRun === true;
  if (!dryRun) fs.mkdirSync(tasksDir, { recursive: true });

  const tasks = [];
  const expected = new Set();
  let generatedBytes = 0;
  for (let index = 0; index < units.length; index += 1) {
    const name = taskFileName(index);
    expected.add(name);
    const file = path.join(tasksDir, name);
    const boundary = validateContainedPath(root, file, {
      allowMissing: true,
      rejectSymlinks: true,
    });
    const content = renderTaskArtifact({
      unit: units[index],
      index,
      planPath: planRelative || CANONICAL_PLAN_RELATIVE_PATH,
      planDigest: digest,
      planningMode: normalized.planning_mode || null,
      planCommit: normalized.plan_commit || null,
      goal: normalized.goal || null,
      nonGoals: normalized.non_goals || [],
    });
    const bytes = Buffer.byteLength(content, "utf8");
    generatedBytes += bytes;
    if (!boundary.ok) {
      tasks.push({
        file: posix(path.join(TASK_ARTIFACT_DIR, name)),
        unit_id: clean(units[index]?.id) || `unit-${index + 1}`,
        status: "REJECTED",
        reason: boundary.reason || "path rejected",
        bytes,
      });
      continue;
    }
    const existing = readIfPresent(file);
    let status;
    if (existing !== null && !isNexusGenerated(existing)) {
      // A hand-written task file is user content: never overwrite it.
      status = "PRESERVED_USER_AUTHORED";
    } else if (existing === content) {
      status = "UNCHANGED";
    } else if (dryRun) {
      status = existing === null ? "WOULD_CREATE" : "WOULD_UPDATE";
    } else {
      try {
        fs.writeFileSync(file, content, "utf8");
        status = existing === null ? "CREATED" : "UPDATED";
      } catch (error) {
        status = "WRITE_FAILED";
        tasks.push({
          file: posix(path.join(TASK_ARTIFACT_DIR, name)),
          unit_id: clean(units[index]?.id) || `unit-${index + 1}`,
          status,
          reason: error?.code || "write error",
          bytes,
        });
        continue;
      }
    }
    tasks.push({
      file: posix(path.join(TASK_ARTIFACT_DIR, name)),
      unit_id: clean(units[index]?.id) || `unit-${index + 1}`,
      status,
      bytes,
      plan_digest: digest,
    });
  }

  // Retire stale views, but only the ones Nexus can prove it generated.
  const removed = [];
  const preserved = [];
  let entries = [];
  try {
    entries = fs.readdirSync(tasksDir, { withFileTypes: true });
  } catch {
    entries = [];
  }
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
    if (expected.has(entry.name)) continue;
    const file = path.join(tasksDir, entry.name);
    const boundary = validateContainedPath(root, file, {
      allowMissing: false,
      rejectSymlinks: true,
    });
    const relative = posix(path.join(TASK_ARTIFACT_DIR, entry.name));
    if (!boundary.ok) {
      preserved.push({ file: relative, reason: "PATH_REJECTED" });
      continue;
    }
    const content = readIfPresent(file);
    if (content === null) {
      preserved.push({ file: relative, reason: "UNREADABLE" });
      continue;
    }
    if (!isNexusGenerated(content)) {
      preserved.push({ file: relative, reason: "USER_AUTHORED" });
      continue;
    }
    if (dryRun) {
      removed.push({ file: relative, status: "WOULD_REMOVE" });
      continue;
    }
    try {
      fs.rmSync(file);
      removed.push({ file: relative, status: "REMOVED" });
    } catch (error) {
      preserved.push({ file: relative, reason: error?.code || "REMOVE_FAILED" });
    }
  }

  const planBytes = Buffer.byteLength(sourceText, "utf8");
  const duration = Date.now() - started;
  const summary = {
    ok: tasks.every(
      (task) => task.status !== "REJECTED" && task.status !== "WRITE_FAILED",
    ),
    version: TASK_ARTIFACT_VERSION,
    generated_view: true,
    plan_path: planRelative || CANONICAL_PLAN_RELATIVE_PATH,
    plan_digest: digest,
    planning_mode: normalized.planning_mode || null,
    unit_count: units.length,
    tasks,
    removed,
    preserved,
    task_materialization_count: tasks.filter(
      (task) =>
        task.status === "CREATED" ||
        task.status === "UPDATED" ||
        task.status === "UNCHANGED",
    ).length,
    generated_task_bytes: generatedBytes,
    plan_bytes: planBytes,
    dry_run: dryRun,
    duration_ms: duration,
  };

  const telemetry = options.telemetry;
  if (typeof telemetry?.emit === "function") {
    telemetry.emit({
      event: "task_materialization",
      run_id: options.runId,
      kind: dryRun ? "dry_run" : "materialize",
      plan_bytes: planBytes,
      generated_task_bytes: generatedBytes,
      task_materialization_count: summary.task_materialization_count,
      duration_ms: duration,
    });
  }

  return summary;
}

/**
 * Check whether the generated views still match the current plan. Used by
 * reconcile: a stale or hand-edited view is reported, never silently trusted.
 */
export function inspectTaskArtifacts(options = {}) {
  const root = path.resolve(options.worktree || process.cwd());
  const result = materializeTaskArtifacts({ ...options, worktree: root, dryRun: true });
  const stale = result.tasks.filter(
    (task) => task.status === "WOULD_CREATE" || task.status === "WOULD_UPDATE",
  );
  return {
    ...result,
    current:
      result.ok &&
      stale.length === 0 &&
      result.removed.length === 0,
    stale_tasks: stale,
  };
}
